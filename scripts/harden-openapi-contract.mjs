const PARAMETER_LIMITS = {
  before: 1024,
  cursor: 1024,
  q: 256,
  range: 128,
  returnTo: 2048,
  t: 8_192,
  token: 1024,
  "user-agent": 512,
  "content-type": 255,
  "sec-fetch-site": 32,
};
const SOURCE_VALIDATION_RESPONSES = new Map([
  ["post /api/billing/checkout", "checkoutRequestSchema"],
  ["post /api/calls/{roomId}/end", "callRoomIdSchema"],
  ["post /api/calls/{roomId}/token", "callRoomIdSchema"],
  ["get /api/conversations/{id}/messages", "messagesQuerySchema"],
]);

function needsStringLimit(schema) {
  return schema?.type === "string" && schema.maxLength == null && schema.enum == null && schema.const == null;
}

function parameterLimit(parameter) {
  const named = PARAMETER_LIMITS[parameter.name];
  if (named) return named;
  if (parameter.in === "path") return 128;
  if (parameter.in === "header") return 1024;
  return 2048;
}

function boundSchema(schema, maxLength) {
  if (!schema || typeof schema !== "object" || schema.$ref) return;
  if (needsStringLimit(schema)) schema.maxLength = maxLength;
  if (schema.items) boundSchema(schema.items, maxLength);
  for (const child of Object.values(schema.properties ?? {})) boundSchema(child, maxLength);
  for (const keyword of ["allOf", "anyOf", "oneOf"]) {
    for (const child of schema[keyword] ?? []) boundSchema(child, maxLength);
  }
}

function boundParameters(parameters = []) {
  for (const parameter of parameters) {
    if (parameter?.schema) boundSchema(parameter.schema, parameterLimit(parameter));
  }
}

function inventory(document) {
  const operations = [];
  for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(pathItem ?? {})) {
      if (METHODS.has(method)) operations.push(`${method} ${path}:${operation.operationId ?? ""}`);
    }
  }
  return {
    paths: Object.keys(document.paths ?? {}).sort(),
    operations: operations.sort(),
    schemas: JSON.stringify(document.components?.schemas ?? {}),
  };
}

export function hardenOpenApiContract(input) {
  const document = structuredClone(input);
  const before = inventory(document);

  document.components ??= {};
  document.components.responses ??= {};
  document.components.responses.RateLimitExceeded = structuredClone(
    RATE_LIMIT_RESPONSE,
  );
  document.components.securitySchemes ??= {};
  document.components.securitySchemes.ReplaySignature = structuredClone(
    REPLAY_SECURITY_SCHEME,
  );
  document.components.securitySchemes.OnboardingAnalyticsConsent =
    structuredClone(ONBOARDING_ANALYTICS_CONSENT_SCHEME);
  document.info ??= {};
  document.info.contact = structuredClone(API_CONTACT);

  if ((document.servers ?? []).some((server) => LOOPBACK.test(server.url))) {
    document.servers = [PRODUCTION_SERVER];
  } else {
    document.servers = (document.servers ?? []).map((server) => ({
      ...server,
      "x-internal": server["x-internal"] ?? false,
    }));
  }

  for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
    boundParameters(pathItem.parameters);
    for (const [method, operation] of Object.entries(pathItem ?? {})) {
      if (!METHODS.has(method)) continue;
      boundParameters(operation.parameters);
      if (path === "/api/media/{id}/blob" && method === "get") {
        operation.parameters = (operation.parameters ?? []).filter(
          (parameter) => !["expires", "token"].includes(parameter.name),
        );
      }
      for (const [mediaType, media] of Object.entries(operation.requestBody?.content ?? {})) {
        boundSchema(media.schema, mediaType === "text/vtt" ? 5_242_880 : 1_048_576);
      }
      if (
        method === "get" &&
        ["/api/media/{id}/blob", "/api/replay/stream"].includes(path)
      ) {
        for (const response of Object.values(operation.responses ?? {})) {
          for (const [mediaType, media] of Object.entries(response.content ?? {})) {
            boundSchema(
              media.schema,
              mediaType === "application/vnd.apple.mpegurl"
                ? 1_048_576
                : 209_715_200,
            );
          }
        }
      }
      if (path === "/api/replay/stream" && method === "get") {
        operation.parameters = structuredClone(REPLAY_PARAMETERS);
        operation.responses["416"] = structuredClone(
          REPLAY_RANGE_ERROR_RESPONSE,
        );
        operation.responses["503"] = structuredClone(
          REPLAY_CAPACITY_RESPONSE,
        );
        operation["x-request-schema-source"] =
          "verifyStreamCapability(t) and normalizeReplayRange in src/app/api/replay/stream/route.ts";
      }
      if (method === "get" && ["/callback", "/sign-in"].includes(path)) {
        for (const response of Object.values(operation.responses ?? {})) {
          if (response.headers?.Location?.schema) {
            boundSchema(response.headers.Location.schema, 8_192);
          }
          response.headers = {
            ...(response.headers ?? {}),
            "Access-Control-Allow-Origin": {
              description: "Exact GreyhoundIQ production origin for the authentication redirect contract.",
              schema: {
                type: "string",
                enum: ["https://greyhoundsiq.com.au"],
              },
            },
          };
        }
      }
      const validationSource = SOURCE_VALIDATION_RESPONSES.get(`${method} ${path}`);
      if (validationSource) {
        operation.responses["400"] ??= {
          description: `The request failed source Zod validation in ${validationSource}.`,
          content: {
            "application/json": {
              schema: { $ref: "#/components/schemas/UnspecifiedJsonObject" },
            },
          },
        };
      }
    }
  }

  assert.deepEqual(inventory(document), before, "OpenAPI paths, operations, or component schemas changed");
  return document;
}

function main() {
  const file = new URL("../openapi.json", import.meta.url);
  const current = JSON.parse(readFileSync(file, "utf8"));
  const hardened = hardenOpenApiContract(current);
  const output = `${JSON.stringify(hardened, null, 2)}\n`;

  if (process.argv.includes("--check")) {
    assert.equal(readFileSync(file, "utf8"), output, "openapi.json needs npm run harden:openapi-contract");
    console.log("OpenAPI contract hardening check passed.");
    return;
  }
  if (!process.argv.includes("--write")) throw new Error("Use --check or --write");
  writeFileSync(file, output);
  console.log("OpenAPI contract hardened without changing paths, operations, or component schemas.");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
